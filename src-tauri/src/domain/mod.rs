//!
//! # 领域层 (Domain Layer)
//!
//! 本模块实现了应用程序的核心领域逻辑，采用领域驱动设计 (DDD) 的分层架构。
//! 领域层是整个应用程序的核心，包含了业务规则、领域模型和领域服务。
//!
//! ## 模块组织
//!
//! 本模块包含以下子模块：
//!
//! ### auth - 认证管理
//!
//! 负责管理邮件账号的认证凭证，包括：
//! - 密码认证（传统用户名/密码）
//! - OAuth2 认证（Google、Outlook 等）
//! - Token 缓存和自动刷新
//! - 系统密钥环 (Keyring) 集成
//!
//! 主要类型：
//! - `AuthManager`: 认证管理器，提供统一的凭证获取接口
//! - `Credentials`: 凭证类型枚举（密码或 OAuth2 令牌）
//!
//! ### providers - 邮件服务提供商
//!
//! 定义了各种邮件服务提供商的配置和行为，包括：
//! - 个人邮箱（Gmail、Outlook、QQ邮箱、163邮箱等）
//! - 企业邮箱（自建域名邮箱）
//! - OAuth2 配置
//! - IMAP/SMTP 服务器配置
//! - 文件夹映射
//!
//! 主要类型：
//! - `MailProvider`: 邮件服务提供商 trait，定义统一接口
//! - `ProviderInfo`: 服务商基本信息
//! - `ProviderPool`: 服务商池，管理所有已注册的服务商
//!
//! ### sync - 邮件同步
//!
//! 负责与邮件服务器的同步操作，包括：
//! - 全量同步（首次同步或重建索引）
//! - 增量同步（基于 UID 的差异同步）
//! - 同步进度通知
//! - 同步调度（定时自动同步）
//!
//! 主要类型：
//! - `SyncScheduler`: 同步调度器，管理定时同步任务
//! - `SyncOrchestrator`: 同步编排器，协调同步流程
//! - `SyncProgress`: 同步进度信息
//!
//! ## 设计原则
//!
//! 1. **领域独立性**: 领域层不依赖任何外部框架或基础设施，保持业务逻辑的纯粹性
//! 2. **统一语言**: 使用业务领域的术语命名类型和方法
//! 3. **封装性**: 内部实现细节对外部隐藏，只暴露必要的接口
//!
//! ## 依赖关系
//!
//! ```text
//! Domain Layer
//! ├── auth (认证管理)
//! │   ├── 依赖: infrastructure/auth (OAuth2 实现)
//! │   └── 依赖: infrastructure/storage (凭证存储)
//! ├── providers (服务提供商)
//! │   └── 独立: 纯领域模型，无外部依赖
//! └── sync (同步)
//!     ├── 依赖: infrastructure/protocols (IMAP 协议)
//!     └── 依赖: infrastructure/storage (数据持久化)
//! ```
//!
//! ## 使用示例
//!
//! ```rust,ignore
//! // 获取账号的认证凭证
//! let credentials = auth_manager.get_credentials(account_id).await?;
//!
//! // 检测邮箱服务商
//! let provider = ProviderPool::global().detect(&email);
//!
//! // 启动同步
//! sync_scheduler.start();
//! ```

// ========== 子模块声明 ==========

/// 认证管理模块
///
/// 提供邮件账号的认证凭证管理功能，支持密码和 OAuth2 两种认证方式。
pub mod auth;

/// 邮件服务提供商模块
///
/// 定义各种邮件服务提供商的配置和行为，包括服务器设置和认证信息。
pub mod providers;

/// 邮件同步模块
///
/// 实现与邮件服务器的同步功能，包括全量同步、增量同步和进度通知。
pub mod sync;
