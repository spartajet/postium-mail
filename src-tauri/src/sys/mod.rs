//!
//! # 系统模块 (System Module)
//!
//! 本模块提供与操作系统交互的系统级功能，是应用程序与底层系统之间的桥梁。
//!
//! ## 模块组织
//!
//! ### log - 日志系统
//!
//! 提供应用程序的日志记录功能，包括：
//! - 日志初始化和配置
//! - 日志级别管理（TRACE、DEBUG、INFO、WARN、ERROR）
//! - 日志格式化输出
//! - 日志文件轮转
//!
//! 使用 `tracing` 库实现结构化日志，支持：
//! - 控制台输出（开发模式）
//! - 文件输出（生产模式）
//! - 异步日志写入，不影响主线程性能
//!
//! ### tray - 系统托盘
//!
//! 提供系统托盘（任务栏通知区域）功能，包括：
//! - 托盘图标显示
//! - 右键菜单（显示窗口、退出应用等）
//! - 托盘点击事件处理
//! - 最小化到托盘
//!
//! 使用 Tauri 的系统托盘 API 实现，支持：
//! - Windows 系统托盘
//! - macOS 菜单栏图标
//! - Linux 系统托盘
//!
//! ## 设计原则
//!
//! 1. **平台适配**: 自动适配不同操作系统的行为和外观
//! 2. **用户友好**: 提供直观的系统交互方式
//! 3. **资源节约**: 最小化系统资源占用
//! 4. **非阻塞**: 所有系统操作都是异步的，不影响 UI 响应
//!
//! ## 使用示例
//!
//! ```rust,ignore
//! // 初始化日志系统（在应用启动时调用）
//! sys::log::setup_logging();
//!
//! // 设置系统托盘（在 Tauri setup 中调用）
//! sys::tray::setup_tray(app)?;
//! ```
//!

/// 日志系统模块
///
/// 提供日志初始化和配置功能，使用 tracing 库实现结构化日志。
pub mod log;

/// 系统托盘模块
///
/// 提供系统托盘图标和右键菜单功能，支持最小化到托盘。
pub mod tray;
